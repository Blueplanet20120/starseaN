#ifndef STARSEAD_MARKS_H
#define STARSEAD_MARKS_H

#define STARSEAD_PRIMARY_MARK 0x20000000
#define STARSEAD_MARK_MASK 0x60000000

/* Wire contract shared with the enhancement module and BPF2SOCKS.
 * The classified bit is reserved for Asterisk DNS decisions. Proxy sockets
 * carry the final routing mark before their first route lookup. */
#define STARSEAD_DNS_CLASSIFIED_BIT 0x1000000
#define STARSEAD_DNS_PROXY_DECISION STARSEAD_DNS_PROXY_ROUTE_MARK
#define STARSEAD_DNS_DIRECT_MARK 0x41000000
#define STARSEAD_DNS_PROXY_ROUTE_MARK 0x21000000
#define STARSEAD_DNS_MARK_MASK 0x61000000

#define STARSEAD_MARK_STRINGIFY_RAW(value) #value
#define STARSEAD_MARK_STRINGIFY(value) STARSEAD_MARK_STRINGIFY_RAW(value)
#define STARSEAD_MARK_MATCH(value, mask) \
    STARSEAD_MARK_STRINGIFY(value) "/" STARSEAD_MARK_STRINGIFY(mask)

#define STARSEAD_ROUTE_MATCH STARSEAD_MARK_MATCH(STARSEAD_PRIMARY_MARK, STARSEAD_MARK_MASK)
#define STARSEAD_DNS_CLASSIFIED_MATCH \
    STARSEAD_MARK_MATCH(STARSEAD_DNS_CLASSIFIED_BIT, STARSEAD_DNS_CLASSIFIED_BIT)
#define STARSEAD_DNS_PROXY_DECISION_MATCH \
    STARSEAD_MARK_MATCH(STARSEAD_DNS_PROXY_DECISION, STARSEAD_DNS_MARK_MASK)
#define STARSEAD_DNS_DIRECT_MATCH \
    STARSEAD_MARK_MATCH(STARSEAD_DNS_DIRECT_MARK, STARSEAD_DNS_MARK_MASK)
#define STARSEAD_DNS_PROXY_ROUTE_MATCH \
    STARSEAD_MARK_MATCH(STARSEAD_DNS_PROXY_ROUTE_MARK, STARSEAD_DNS_MARK_MASK)

#endif
